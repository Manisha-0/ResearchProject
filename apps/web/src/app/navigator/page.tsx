"use client";

import { RotateCcw } from "lucide-react";
import { PatientRow } from "@/components/navigator/PatientRow";
import { PrioritySummary } from "@/components/navigator/PrioritySummary";
import { computePriority } from "@/lib/scoring";
import { useCompassStore } from "@/store/compass-store";
import { AppHeader } from "@/components/app/AppHeader";

export default function NavigatorDashboard() {
  const patients = useCompassStore((state) => state.patients);
  const resetDemo = useCompassStore((state) => state.resetDemo);

  const rankedPatients = [...patients].sort(
    (a, b) => computePriority(b).score - computePriority(a).score,
  );

  const priorities = patients.map((patient) => computePriority(patient));
  const high = priorities.filter((priority) => priority.tier === "high").length;

  const medium = priorities.filter(
    (priority) => priority.tier === "medium",
  ).length;

  const low = priorities.filter((priority) => priority.tier === "low").length;

  return (
    <main className="min-h-screen bg-surface-soft">
      <AppHeader currentRole="navigator" showReset />
      <header className="border-b border-border bg-white">
        <div className="mx-auto flex max-w-6xl items-center justify-between px-5 py-4 sm:px-8">
          <div className="flex items-center gap-3">
            <div
              className="
                flex
                h-9
                w-9
                items-center
                justify-center
                rounded-xl
                bg-navy
                text-lg
                font-bold
                text-white
              "
            >
              C
            </div>

            <div>
              <div className="font-semibold text-navy">Compass</div>

              <div className="text-xs text-ink-soft">
                Cancer care navigation
              </div>
            </div>
          </div>

          <div className="flex items-center gap-3">
            <span
              className="
                hidden
                rounded-full
                bg-gold-tint
                px-3
                py-1.5
                text-xs
                font-semibold
                text-navy-deep
                sm:block
              "
            >
              Demo · Synthetic Data
            </span>

            <button
              type="button"
              onClick={resetDemo}
              className="
                inline-flex
                items-center
                gap-2
                rounded-lg
                border
                border-border
                bg-white
                px-3
                py-2
                text-sm
                font-medium
                text-ink-soft
                hover:border-navy/25
                hover:text-navy
              "
            >
              <RotateCcw className="h-4 w-4" />
              <span className="hidden sm:inline">Reset demo</span>
            </button>
          </div>
        </div>
      </header>

      <div className="mx-auto max-w-6xl px-5 py-8 sm:px-8 sm:py-10">
        <section>
          <p className="text-sm font-semibold text-gold">
            NAVIGATOR ACTION CENTER
          </p>

          <div className="mt-2 max-w-2xl">
            <h1 className="font-display text-3xl font-bold tracking-tight text-navy-deep sm:text-4xl">
              Good afternoon, James.
            </h1>

            <p className="mt-3 text-base leading-7 text-ink-soft">
              Here&apos;s where your attention may be needed today.
            </p>
          </div>
        </section>

        <section className="mt-8">
          <PrioritySummary high={high} medium={medium} low={low} />
        </section>

        <section className="mt-10">
          <div className="flex items-end justify-between">
            <div>
              <h2 className="text-lg font-semibold text-ink">
                Patients needing attention
              </h2>

              <p className="mt-1 text-sm text-ink-soft">
                Ranked by navigation priority.
              </p>
            </div>
          </div>

          <div className="mt-5 space-y-3">
            {rankedPatients.map((patient) => (
              <PatientRow key={patient.id} patient={patient} />
            ))}
          </div>
        </section>

        <footer className="mt-10 border-t border-border pt-5">
          <p className="text-xs leading-5 text-ink-soft">
            Prototype uses synthetic patient data. Navigation Priority is
            generated by transparent demo rules and is not a clinically
            validated risk score.
          </p>
        </footer>
      </div>
    </main>
  );
}
